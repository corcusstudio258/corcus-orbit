async function call(token, method, path, body, headers = {}) {
  const isForm = body instanceof FormData;
  const r = await fetch(BASE + path, { method, headers: { ...(isForm ? {} : { 'Content-Type': 'application/json' }), ...(token ? { Authorization: `Bearer ${token}` } : {}), Origin: 'http://localhost:5173', ...headers }, body: body ? (isForm ? body : JSON.stringify(body)) : undefined });
  const text = await r.text();
  let data; try { data = JSON.parse(text); } catch { data = text; }
  return { status: r.status, data };
}
